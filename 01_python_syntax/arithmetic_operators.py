#  加减乘除运算

num1 = 10
num2 = 3
print(num1 + num2)
print(num1 - num2)
print(num1 * num2)
print(num1 / num2)   # 除法
print(num1 % num2)   # 取余数
print(num1 // num2)  # 取整数
print(num1 ** num2)  # 次方-幂

# 运算优先级
print(10 + 5 * 2)
print((10 + 5) * 2)

# 批量赋值
n1, n2, n3 = 1, 2, 3
print(n1, n2, n3)

# 复合赋值运算符示例
num = 10
print(num)  # 输出：10

num += 1
print(num)  # 输出：11

num -= 2
print(num)  # 输出：9

num *= 3
print(num)  # 输出：27

num /= 3
print(num)  # 输出：9.0
